class PackingTests(unittest.TestCase):
    def test_stays_in_printable_area(self) -> None:
        packed = pack_copies(50, 50, 220, 220, 9, 8)
        self.assertGreaterEqual(packed.quantity, 9)
        for part in packed.placed:
            self.assertGreaterEqual(part.x, -1e-6)
            self.assertGreaterEqual(part.y, -1e-6)
            self.assertLessEqual(part.x + part.w, 220.001)
            self.assertLessEqual(part.y + part.h, 220.001)
        self.assertFalse(validate_plate(packed))

    def test_rotation_can_beat_axis_aligned_grid(self) -> None:
        packed = pack_copies(80, 30, 220, 100, 20, 8)
        self.assertGreaterEqual(packed.quantity, 6)
        self.assertTrue(any(p.rotation_z in (90.0, 270.0) for p in packed.placed) or packed.quantity >= 6)

    def test_spacing_changes_max_qty(self) -> None:
        tight = max_quantity(20, 20, 100, 100, 2)
        wide = max_quantity(20, 20, 100, 100, 30)
        self.assertGreater(tight, wide)
        self.assertGreaterEqual(tight, 16)
        self.assertEqual(wide, 4)

    def test_slider_count_is_not_forced_to_fill(self) -> None:
        packed = pack_copies(20, 20, 100, 100, 3, 6)
        self.assertEqual(packed.quantity, 3)
        self.assertGreater(packed.max_quantity, 3)
        self.assertEqual(packed.spacing_mm, 6)

    def test_full_plate_sits_at_max_quantity(self) -> None:
        max_q = max_quantity(20, 20, 100, 100, 8)
        filled = pack_copies(20, 20, 100, 100, copies_to_pack(None, True, max_q), 8)
        self.assertGreater(max_q, 1)
        self.assertEqual(filled.quantity, max_q)
        self.assertEqual(filled.max_quantity, max_q)
        self.assertEqual(filled.spacing_mm, 8)

    def test_copies_to_pack_full_plate_is_max(self) -> None:
        self.assertEqual(copies_to_pack(None, False, 12), 12)
        self.assertEqual(copies_to_pack(4, True, 12), 12)
        self.assertEqual(copies_to_pack(4, False, 12), 4)
        self.assertEqual(copies_to_pack(1, False, 1), 1)

    def test_keepout_blocks_corner(self) -> None:
        packed = pack_copies(
            40,
            40,
            100,
            100,
            8,
            6,
            keepouts=[{"x": 0, "y": 0, "w": 50, "h": 50}],
        )
        for part in packed.placed:
            overlap_x = part.x < 50 and part.x + part.w > 0
            overlap_y = part.y < 50 and part.y + part.h > 0
            self.assertFalse(overlap_x and overlap_y)

    def test_even_plates_avoid_leftover_one(self) -> None:
        greedy = plan_plates(43, 14, "balanced")
        even = plan_plates(43, 14, "minimum_bed_clears")
        self.assertEqual(sum(greedy), 43)
        self.assertEqual(sum(even), 43)
        self.assertGreaterEqual(min(even), 10)

    def test_spacing_hint(self) -> None:
        self.assertEqual(spacing_hint(3, 6), "Tight")
        self.assertEqual(spacing_hint(6, 6), "Recommended")
        self.assertEqual(spacing_hint(14, 6), "Conservative")

    def test_clamp(self) -> None:
        self.assertEqual(clamp_spacing(1), 2)
        self.assertEqual(clamp_spacing(40), 30)


class CostAndMetaTests(unittest.TestCase):
    def test_grams_times_price(self) -> None:
        line = filament_line_cost(100, 0.024)
        self.assertTrue(line["costed"])
        self.assertAlmostEqual(line["filament_cost"], 2.4)

    def test_selected_density_not_generic_plastic(self) -> None:
        comments = (
            "; generated by PrusaSlicer 2.7.4\n"
            "; filament used [cm3] = 10.00\n"
            "; filament used [mm] = 4000\n"
            "; estimated printing time (normal mode) = 1h 0m 0s\n"
        )
        meta = parse_gcode_comments(comments)
        pla = grams_from_slicer_meta(meta, 1.24)
        petg = grams_from_slicer_meta(meta, 1.27)
        self.assertIsNotNone(pla[0])
        self.assertIsNotNone(petg[0])
        self.assertNotAlmostEqual(pla[0], petg[0])
        self.assertAlmostEqual(petg[0], 12.7, places=1)


