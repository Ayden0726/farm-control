    def test_nozzle_mismatch_reason(self) -> None:
        class P:
            name = "K1 Max"
            is_enabled = True
            current_downtime_reason = None
            status = type("S", (), {"value": "idle", "__eq__": lambda self, o: True})()
            usable_x_mm = 290
